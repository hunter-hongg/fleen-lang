//! 0.0.8 D16 empirical pin (review fix): the shipped std crate compiles
//! byte-identically to the released 0.0.7 compiler. The T09 ticket records
//! std byte-identity as asserted structurally (every std file flag-off in
//! the `FeatureTable`); this test upgrades it to an empirical one.
//!
//! Mechanism: the same probe program is compiled through HEAD and through a
//! v0.0.7 checkout (`git archive v0.0.7`, then the probe run against it) —
//! the two dumps were diffed identical before pinning (LESSON L3: no
//! unverified byte claim is written down). The probe registers a root file
//! `import std.io` + `func main(): int = 0` (the stub is identical in both
//! trees, so the std contribution is what is compared), runs
//! `Session::compile_project`, and hex-encodes the module stream. The
//! expected string is the v0.0.7 dump verbatim: the `len=` header followed
//! immediately by the hex (no separator).
//!
//! Regen: re-run the probe under a fresh v0.0.7 checkout, diff against
//! HEAD's dump, then replace the constant.
