#[test]
fn std_module_is_byte_identical_with_0_0_7() {
    let mut session = Session::new();
    let root = session.add_file("probe_main.fln", ROOT_SRC);
    let module = session
        .compile_project(root)
        .expect("std+stub probe compiles");
    assert_eq!(module.version, 7, "std-only module stays bytecode v7");
    let bytes = to_bytes(&module);
    let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    let actual = format!("len={} version={}{}", bytes.len(), module.version, hex);
    assert_eq!(
        actual, V007_STD_PROBE_EXPECTED,
        "std bytecode diverged from the released 0.0.7 compiler (D16)"
    );
}
